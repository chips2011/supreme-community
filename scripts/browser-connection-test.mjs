import assert from 'node:assert/strict';
import { browserConnectionEvidence, browserRecoveryPrompt, createBrowserConnectionMonitor } from '../lib/browser-connection.mjs';

let checks = 0;
const check = (value, label) => { assert.ok(value, label); checks++; console.log(`ok ${label}`); };
const failure = (extra = {}) => ({ id: 'lost', server: 'node_repl', tool: 'js', status: 'failed', error: { message: 'Browser is not available: chrome' }, ...extra });
const success = (backend = 'chrome') => ({ id: 'live', server: 'node_repl', tool: 'js', status: 'completed', result: { _meta: { 'codex/toolSurface': { backend, kind: 'browserUse' } } } });
const flush = () => new Promise(resolve => setImmediate(resolve));
check(browserConnectionEvidence(failure())?.state === 'unavailable', 'structured provider error is detected');
check(browserConnectionEvidence(failure({ error: null, status: 'failed', result: { content: [{ type: 'text', text: 'No browser is available' }], isError: true } }))?.family === 'browser', 'actual Codex 0.163.0 no-browser failure is detected without inventing a selected browser');
check(browserConnectionEvidence(failure({ error: null, status: 'failed', arguments: { code: "const chrome = await agent.browsers.get('chrome');" }, result: { content: [{ type: 'text', text: 'No browser is available' }], isError: true } }))?.family === 'chrome', 'explicit Chrome selection remains Chrome with a generic error');
check(browserConnectionEvidence(failure({ error: null, status: 'completed', result: { content: [{ type: 'text', text: 'Elapsed: 0.1 seconds\nOutput:\nError: Browser is not available: chrome' }] } }))?.state === 'unavailable', 'Node REPL thrown-error envelope is detected without isError');
check(browserConnectionEvidence(failure({ error: null, result: { isError: true, content: [{ type: 'text', text: 'Cannot communicate with the ChatGPT browser extension' }] } }))?.state === 'unavailable', 'extension communication failure is detected');
check(browserConnectionEvidence(failure({ error: 'Browser is not available: edge' }))?.family === 'edge', 'Edge remains Edge');
check(!browserConnectionEvidence(failure({ error: 'Browser is not available: iab' })), 'in-app browser is not replaced with Chrome');
check(!browserConnectionEvidence(failure({ server: 'slack', tool: 'read', error: 'Browser is not available: chrome' })), 'connector content cannot trigger browser recovery');
check(!browserConnectionEvidence(failure({ error: null, status: 'completed', result: { content: [{ type: 'text', text: 'The page says Browser is not available: chrome' }] } })), 'page prose is not connection evidence');
check(!browserConnectionEvidence(failure({ error: null, status: 'completed', result: { content: [{ type: 'text', text: 'The documentation shows this example:\nError: Browser is not available: chrome' }] } })), 'quoted documentation must not trigger recovery');
check(!browserConnectionEvidence({ ...success(), status: 'failed', error: 'Permission denied' }), 'failed call with browser metadata cannot report healthy');
check(!browserConnectionEvidence({ server: 'node_repl', tool: 'js', status: 'completed', result: { content: [{ type: 'text', text: '{"valid":true}' }] } }), 'passing install diagnostics are not live browser evidence');
check(browserConnectionEvidence(success())?.state === 'connected', 'trusted live browser metadata is connection evidence');

const events = [], prompts = [];
let timeout, clears = 0;
const timers = { setTimeout: callback => { timeout = callback; return 1; }, clearTimeout: () => { clears++; } };
const monitor = createBrowserConnectionMonitor({ emit: e => events.push(e), recover: async p => { prompts.push(p); return true; }, timers });
monitor.observe(failure());
await flush();
check(events.map(e => e.connection).join(',') === 'unavailable,recovering', 'failure transitions into bounded recovery');
check(prompts.length === 1 && prompts[0].includes('same-profile reopen once'), 'native recovery request is issued once');
check(!JSON.stringify(events).includes('Browser is not available'), 'raw provider error stays out of public events');
monitor.observe(failure());
await flush();
check(prompts.length === 1 && events.length === 2, 'duplicate failed tool completion is idempotent');
monitor.observe({ server: 'node_repl', tool: 'js', status: 'completed', result: {} });
check(events.at(-1).connection === 'recovering', 'unrelated JS success does not clear recovery');
monitor.observe(success('edge'));
check(events.at(-1).connection === 'recovering', 'another browser cannot clear selected browser failure');
monitor.observe(success());
check(events.at(-1).connection === 'connected' && clears > 0, 'real browser success clears the timeout and failure');
monitor.observe(failure({ id: 'lost-again' }));
await flush();
check(events.at(-1).connection === 'unavailable' && prompts.length === 1, 'second disconnect does not create a recovery loop');
monitor.finish();
const count = events.length;
monitor.observe(success());
check(events.length === count, 'late success cannot mutate a completed run');

const timed = [];
const timing = createBrowserConnectionMonitor({ emit: e => timed.push(e), recover: async () => true, timers });
timing.observe(failure()); await flush(); timeout();
check(timed.at(-1).connection === 'unavailable', 'recovery expires without a live browser receipt');
timing.finish();
const end = [];
const ending = createBrowserConnectionMonitor({ emit: e => end.push(e), recover: async () => true, timers });
ending.observe(failure()); ending.finish(); await flush();
check(end.at(-1).connection === 'unavailable', 'turn ending mid-recovery stays blocked');
const rejected = [];
const rejecting = createBrowserConnectionMonitor({ emit: e => rejected.push(e), recover: async () => false, timers });
rejecting.observe(failure()); await flush();
check(rejected.at(-1).connection === 'unavailable', 'rejected steering does not retry the user task');
rejecting.finish();
const throwing = [];
const throws = createBrowserConnectionMonitor({ emit: e => throwing.push(e), recover: async () => { throw Error('closed'); }, timers });
throws.observe(failure()); await flush();
check(throwing.at(-1).connection === 'unavailable', 'steer transport exception is contained');
throws.finish();
const compatibility = [];
const exec = createBrowserConnectionMonitor({ emit: e => compatibility.push(e), timers });
exec.observe(failure()); exec.finish();
check(compatibility.length === 1 && compatibility[0].connection === 'unavailable', 'exec compatibility mode reports blocked without pretending to steer');
const guidance = browserRecoveryPrompt('edge');
check(guidance.includes('Keep Edge') && guidance.includes('already selected profile/account'), 'recovery preserves the browser/account constraint');
check(guidance.includes('Never replay a possibly completed mutation'), 'recovery checks pending writes instead of replaying them');
check(guidance.includes('Do not repeat a recovery step already attempted'), 'recovery respects the per-turn attempt budget');
console.log(`BROWSER CONNECTION UNITS: PASS (${checks})`);
