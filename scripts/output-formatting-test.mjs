import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import * as writtenOutput from '../lib/written-output.mjs';
import { outputImageReferences, publicOutputImages, readOutputImage } from '../lib/output-images.mjs';

const require = createRequire(new URL('../web/package.json', import.meta.url));
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const source = fs.readFileSync(new URL('../web/src/lib/writtenText.tsx', import.meta.url), 'utf8');
const js = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX },
}).outputText;
const context = { exports: {}, require: name => name.endsWith('/written-output.mjs') ? writtenOutput : require(name), URL };
vm.runInNewContext(js, context);
const { WrittenText, normalizeCodexCitations, parseWrittenBlocks } = context.exports;
const render = (value, images) => renderToStaticMarkup(React.createElement(WrittenText, { value, images, inferWorkNotes: false }));
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log(`ok ${label}`); };

const home = fs.mkdtempSync(path.join(os.tmpdir(), 'supreme-output-formatting-unit-'));
const local = path.join(home, 'status colors (updated).png');
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64');
fs.writeFileSync(local, png);
const content = `Done, the status dropdowns are now color coded.\n\n:codex-file-citation{path="https://docs.google.com/spreadsheets/d/test/edit?usp=drivesdk" purpose="output"}\n\n![Colored statuses](<${local}>)`;
const images = publicOutputImages(content, 'task', 'tab');
check(normalizeCodexCitations(content) === writtenOutput.normalizeWrittenOutput(content), 'provider and frontend share normalization');
check(parseWrittenBlocks(normalizeCodexCitations(content)).at(-1).type === 'image', 'screenshot is an image block');
const html = render(content, images);
check(html.includes('href="https://docs.google.com/spreadsheets/d/test/edit?usp=drivesdk"') && html.includes('Google Sheets'), 'document link has a readable label and complete URL');
check(html.includes('<img ') && html.includes('alt="Colored statuses"') && html.includes(images[0].url), 'actual renderer produces a private screenshot preview');
check(!html.includes(':codex-file-citation') && !html.includes('!Colored'), 'provider syntax does not leak into the answer');
check(render('![Missing](/tmp/missing.png)').includes('Unavailable on this computer'), 'missing image is readable without broken Markdown');
check(!render('![Unsafe](javascript:alert)').includes('<img') && !render('![Unsafe](javascript:alert)').includes('href='), 'unsafe image protocols cannot load or link');
check(!render('![Remote](https://example.com/image.png)').includes('<img') && render('![Remote](https://example.com/image.png)').includes('href='), 'remote images are links, not automatic tracking requests');
check(!render('![Forged](/tmp/forged.png)', [{ target: '/tmp/forged.png', url: 'https://example.com/tracker.png' }]).includes('<img'), 'untrusted preview URLs never load');
check(render('```md\n![Example](/tmp/example.png)\n```').includes('![Example](/tmp/example.png)'), 'fenced Markdown remains copyable code');
const served = await readOutputImage({ messages: [{ role: 'assistant', content }] }, outputImageReferences(content)[0].id);
check(served?.mimeType === 'image/png' && served.bytes.equals(png), 'referenced raster is read from a bounded verified buffer');
check(await readOutputImage({ messages: [] }, images[0].url.split('/').at(-1)) === null, 'unreferenced image ID is denied');
check(await readOutputImage({ messages: [{ role: 'user', content }] }, images[0].url.split('/').at(-1)) === null, 'user text does not authorize serving a filesystem image');
check(await readOutputImage({ messages: [{ role: 'assistant', content }] }, '../status.png') === null, 'path traversal is denied');
const fake = path.join(home, 'not-an-image.png');
fs.writeFileSync(fake, '<script>alert(1)</script>');
const fakeContent = `![Fake](${fake})`;
check(await readOutputImage({ messages: [{ role: 'assistant', content: fakeContent }] }, outputImageReferences(fakeContent)[0].id) === null, 'HTML renamed to PNG is denied');
const big = path.join(home, 'too-large.png');
fs.writeFileSync(big, Buffer.alloc(10 * 1024 * 1024 + 1));
const bigContent = `![Big](${big})`;
check(await readOutputImage({ messages: [{ role: 'assistant', content: bigContent }] }, outputImageReferences(bigContent)[0].id) === null, 'oversized files are denied');
const symlink = path.join(home, 'symlink.png');
fs.symlinkSync(local, symlink);
const linkedContent = `![Linked](${symlink})`;
check(await readOutputImage({ messages: [{ role: 'assistant', content: linkedContent }] }, outputImageReferences(linkedContent)[0].id) === null, 'final-component symlinks are denied');
check(!outputImageReferences('```md\n![Example](/tmp/example.png)\n```').length, 'code examples do not authorize file access');
check(outputImageReferences('![SVG](/tmp/example.svg)').length === 0, 'active image formats are excluded');
check(!outputImageReferences('![Network](//example.com/file.png)').length, 'network paths are excluded');
console.log(`OUTPUT FORMATTING: PASS (${checks})`);
console.log(`Evidence retained: ${home}`);
