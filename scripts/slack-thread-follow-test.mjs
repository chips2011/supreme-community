import assert from 'node:assert/strict';
import { slackThreadInvited, slackThreadAcknowledgment, authorizeSlackThreadSteer } from '../lib/slack-thread-follow.mjs';
let checks = 0;
const check = (ok, label) => { assert.ok(ok, label); checks++; console.log(`ok ${label}`); };
const root = '1792400000.000001', ts = '1792400001.000001', bot = 'UBOT';
check(slackThreadInvited([{ ts: root, user: 'U1', text: '<@UBOT> investigate this' }], root, bot), 'a genuine original mention subscribes its thread');
check(slackThreadInvited([{ ts, thread_ts: root, user: 'U1', text: '<@UBOT> join here' }], root, bot), 'a mention in an existing thread invites the agent');
check(slackThreadInvited([{ ts, thread_ts: root, user: bot, bot_id: 'B1', text: 'On it.' }], root, bot), 'Supreme participation can re-establish the subscription on another Mac');
check(!slackThreadInvited([{ ts: root, user: 'U1', text: 'unrelated chat' }], root, bot), 'uninvited thread does not activate the agent');
check(!slackThreadInvited([{ ts: 'other-root', user: 'U1', text: '<@UBOT> join' }], root, bot), 'another thread cannot establish participation');
check(!slackThreadInvited([{ ts: root, user: 'U1', edited: {}, text: '<@UBOT> edited' }], root, bot), 'edited text cannot create a fresh invitation');
check(!slackThreadInvited([{ ts: root, user: 'UOTHERBOT', bot_id: 'BOTHER', text: '<@UBOT> loop' }], root, bot), 'another bot cannot activate a conversation loop');
check(slackThreadAcknowledgment('thanks!'), 'simple thanks do not consume a model turn');
check(slackThreadAcknowledgment('ok'), 'simple acknowledgement stays quiet');
check(!slackThreadAcknowledgment('thanks, how many fit?'), 'a real question still reaches Supreme');
check(!slackThreadAcknowledgment('yes send it'), 'an approval is not discarded as an acknowledgement');
check(!slackThreadAcknowledgment('thanks', [{ id: 'F1' }]), 'a message carrying a file is retained');
const source = { channel: 'C1', threadTs: root, user: { id: 'U1', name: 'Alex' } };
const claimed = { channel: 'C1', threadTs: root, ts, user: { id: 'U2' } };
let verified = { channel: 'C1', thread_ts: root, ts, user: 'U2', text: 'Is this expected?' }, allowed = true;
const allow = (overrides = {}) => authorizeSlackThreadSteer({ source, claimed, task: {}, readRequest: async () => verified, mayUse: async () => allowed, userName: async () => 'Casey', ...overrides });
check((await allow())?.user.name === 'Casey', 'authorized teammate can join the same live conversation under their own identity');
allowed = false;
check(await allow() === null, 'thread membership alone does not grant project access');
allowed = true; verified = { ...verified, user: 'USTRANGER' };
check(await allow() === null, 'claimed author cannot replace Slack-authenticated author');
verified = { ...verified, user: 'U2', thread_ts: 'another-root' };
check(await allow() === null, 'verified message must belong to the same root');
verified = { ...verified, thread_ts: root, ts: 'another-message' };
check(await allow() === null, 'verified message timestamp must match the requested steer');
check(await allow({ source: { ...source, channel: 'COTHER' } }) === null, 'wrong channel is refused before verification');
let reads = 0;
check((await allow({ claimed: { ...claimed, user: { id: 'U1' } }, readRequest: async () => { reads++; } }))?.user.id === 'U1' && reads === 0, 'original sender keeps the existing fast path');
console.log(`SLACK THREAD FOLLOW UNITS: PASS (${checks})`);
